use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=src-rust/wv2_shim.c");
    println!("cargo:rerun-if-changed=src-rust/WebView2Loader.dll");
    println!("cargo:rerun-if-changed=src-rust/app.rc");
    println!("cargo:rerun-if-changed=src-rust/icon.ico");
    println!("cargo:rerun-if-changed=src-rust/pdf_doc.ico");
    println!("cargo:rerun-if-changed=src-rust/assets/index.html");
    println!("cargo:rerun-if-changed=src-rust/assets/assets/index-11jbxaY0.js");
    println!("cargo:rerun-if-changed=src-rust/assets/assets/index-ClXAvMiX.css");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let obj_path = out_dir.join("wv2_shim.o");
    let res_obj_path = out_dir.join("app_res.o");
    let lib_a_path = out_dir.join("libWebView2Loader.dll.a");
    let lib_lib_path = out_dir.join("WebView2Loader.dll.lib");

    let res_status = Command::new("windres")
        .args([
            "src-rust/app.rc",
            "-O",
            "coff",
            "-o",
            res_obj_path.to_str().unwrap(),
        ])
        .status()
        .expect("Failed to run windres on src-rust/app.rc");
    assert!(res_status.success(), "windres failed to compile src-rust/app.rc");
    println!("cargo:rustc-link-arg-bins={}", res_obj_path.display());

    let status = Command::new("gcc")
        .args([
            "-O2",
            "-c",
            "src-rust/wv2_shim.c",
            "-o",
            obj_path.to_str().unwrap(),
        ])
        .status()
        .expect("Failed to run gcc on wv2_shim.c");
    assert!(status.success(), "gcc failed to compile wv2_shim.c");

    let ar_status = Command::new("ar")
        .args([
            "rcs",
            lib_a_path.to_str().unwrap(),
            obj_path.to_str().unwrap(),
        ])
        .status()
        .expect("Failed to run ar on wv2_shim.o");
    assert!(ar_status.success(), "ar failed to create libWebView2Loader.dll.a");

    let _ = fs::copy(&lib_a_path, &lib_lib_path);

    // Also replace any dynamic import library generated by webview2-com-sys in the build directory
    // so GNU ld statically links our loader shim instead of adding WebView2Loader.dll to the PE import table.
    if let Some(build_dir) = out_dir.parent().and_then(|p| p.parent()) {
        if let Ok(entries) = fs::read_dir(build_dir) {
            for entry in entries.flatten() {
                let name = entry.file_name().to_string_lossy().to_string();
                if name.starts_with("webview2-com-sys-") {
                    let target_lib = entry
                        .path()
                        .join("out")
                        .join("x64")
                        .join("WebView2Loader.dll.lib");
                    if target_lib.exists() {
                        let _ = fs::copy(&lib_a_path, &target_lib);
                    }
                    let target_a = entry
                        .path()
                        .join("out")
                        .join("x64")
                        .join("libWebView2Loader.dll.a");
                    let _ = fs::copy(&lib_a_path, &target_a);
                }
            }
        }
    }

    println!("cargo:rustc-link-search=native={}", out_dir.display());
}

